const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  authStatus: () => ipcRenderer.invoke('auth:status'),
  login: () => ipcRenderer.invoke('auth:login'),
  logout: () => ipcRenderer.invoke('auth:logout'),
  browse: (id, params) => ipcRenderer.invoke('yt:browse', id, params),
  lyrics: (song) => ipcRenderer.invoke('yt:lyrics', song),
  recordPlay: (song) => ipcRenderer.invoke('stats:play', song),
  stats: () => ipcRenderer.invoke('stats:get'),
  like: (id, liked) => ipcRenderer.invoke('yt:like', id, liked),
  playlistAdd: (pid, vid) => ipcRenderer.invoke('pl:add', pid, vid),
  playlistRemove: (pid, vid) => ipcRenderer.invoke('pl:remove', pid, vid),
  playlistCreate: (title, vid) => ipcRenderer.invoke('pl:create', title, vid),
  radio: (vid) => ipcRenderer.invoke('yt:radio', vid),
  search: (q) => ipcRenderer.invoke('yt:search', q),
  library: () => ipcRenderer.invoke('yt:library'),
  playlist: (id) => ipcRenderer.invoke('yt:playlist', id),
  recommended: () => ipcRenderer.invoke('yt:recommended'),
  stream: (videoId, prio, meta) => ipcRenderer.invoke('yt:stream', videoId, prio, meta),
  dlAdd: (song) => ipcRenderer.invoke('dl:add', song),
  dlRemove: (id) => ipcRenderer.invoke('dl:remove', id),
  dlList: () => ipcRenderer.invoke('dl:list'),
  dlIds: () => ipcRenderer.invoke('dl:ids'),
  syncRecommended: (songs) => ipcRenderer.invoke('yt:syncRecommended', songs),
  playerState: (s) => ipcRenderer.invoke('player:state', s),
  onMedia: (cb) => ipcRenderer.on('media', (_e, a) => cb(a)),
  onProgress: (cb) => ipcRenderer.on('progress', (_e, m) => cb(m)),
  version: () => ipcRenderer.invoke('app:version'),
  restart: () => ipcRenderer.invoke('app:restart'),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, msg) => cb(msg)),
});
